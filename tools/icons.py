# Icons derived from others: name -> (source, transform)
DERIVED: dict[str, tuple[str, str]] = {
    "redo": ("undo", "mirror"),
}


def _lines_icon(widths: list[tuple[int, int]]) -> str:
    """Build an alignment icon from (start, length) pairs for 5 text lines."""
    rows = ["." * 16 for _ in range(16)]
    for i, (start, length) in enumerate(widths):
        y = 2 + i * 2
        rows[y] = "." * start + "k" * length + "." * (16 - start - length)
    return "\n".join(rows)


ICONS["align-left"] = _lines_icon([(2, 12), (2, 8), (2, 12), (2, 8), (2, 12), (2, 8)])
ICONS["align-center"] = _lines_icon([(2, 12), (4, 8), (2, 12), (4, 8), (2, 12), (4, 8)])
ICONS["align-right"] = _lines_icon([(2, 12), (6, 8), (2, 12), (6, 8), (2, 12), (6, 8)])
ICONS["align-justify"] = _lines_icon([(2, 12)] * 6)


def parse(name: str, art: str) -> list[str]:
    rows = [r for r in art.strip("\n").splitlines()]
    width = len(rows[0])
    for i, row in enumerate(rows):
        if len(row) != width:
            raise ValueError(f"icon {name!r}: row {i} has width {len(row)}, expected {width}")
        bad = set(row) - set(PALETTE) - {"."}
        if bad:
            raise ValueError(f"icon {name!r}: unknown colours {bad}")
    return rows


def to_paths(rows: list[str]) -> str:
    by_colour: dict[str, list[str]] = {}
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch == ".":
                x += 1
                continue
            start = x
            while x < len(row) and row[x] == ch:
                x += 1
            by_colour.setdefault(ch, []).append(f"M{start} {y}h{x - start}v1h-{x - start}z")
    return "".join(
        f'<path fill="{PALETTE[ch]}" d="{"".join(segs)}"/>' for ch, segs in by_colour.items()
    )


def build() -> dict[str, tuple[int, int, str]]:
    parsed = {name: parse(name, art) for name, art in ICONS.items()}
    for name, (src, transform) in DERIVED.items():
        if transform == "mirror":
            parsed[name] = [row[::-1] for row in parsed[src]]
    return {name: (len(rows[0]), len(rows), to_paths(rows)) for name, rows in parsed.items()}


def sprite(icons: dict[str, tuple[int, int, str]]) -> str:
    symbols = "\n".join(
        f'<symbol id="i-{name}" viewBox="0 0 {w} {h}">{paths}</symbol>'
        for name, (w, h, paths) in sorted(icons.items())
    )
    return (
        "<!-- GENERATED by tools/icons.py - edit the ASCII art there, not this file. -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges">\n'
        f"{symbols}\n</svg>\n"
    )


def preview(icons: dict[str, tuple[int, int, str]], svg: str) -> str:
    cells = "".join(
        f'<figure><svg width="{w * 1}" height="{h * 1}"><use href="#i-{n}"/></svg>'
        f'<svg width="{w * 4}" height="{h * 4}"><use href="#i-{n}"/></svg><figcaption>{n}</figcaption></figure>'
        for n, (w, h, _) in sorted(icons.items())
    )
    body = svg.split("\n", 1)[1].replace("<svg ", '<svg style="display:none" ', 1)
    return (
        "<!doctype html><style>body{background:#c0c0c0;font:11px Tahoma;display:flex;flex-wrap:wrap;gap:8px}"
        "figure{margin:0;padding:6px;background:#c0c0c0;border:1px solid #808080;text-align:center}"
        "svg{display:block;margin:2px auto}</style>" + body + cells
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview", type=Path, help="write an HTML preview sheet to this path")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    icons = build()
    svg = sprite(icons)
    out = root / "assets" / "icons" / "sprite.svg"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(svg, encoding="utf-8")
    print(f"wrote {len(icons)} icons to {out.relative_to(root)} ({len(svg)} bytes)")
    if args.preview:
        args.preview.write_text(preview(icons, svg), encoding="utf-8")
        print(f"preview: {args.preview}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
